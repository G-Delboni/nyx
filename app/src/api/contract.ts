// UI <-> core contract. Owner: orchestrator. Spec: docs/specs/FASE-0-MVP.md §4.
// Rust mirrors these with serde(rename_all = "camelCase"); enums as lowercase strings.
// Change this file only through the orchestrator.

export type AgentKind = "claude-code";

export type SessionStatus =
  | "running"      // SessionStart / UserPromptSubmit / PreToolUse
  | "waiting"      // Notification: the agent needs the user
  | "done"         // Stop
  | "ended"        // SessionEnd
  | "idle"         // no event for 30 min
  | "error";

export interface AgentSession {
  sessionId: string;
  agent: AgentKind;
  cwd: string | null;
  folderName: string | null;   // last path segment of cwd
  contextId: string | null;
  status: SessionStatus;
  startedAt: string;           // RFC3339
  updatedAt: string;           // RFC3339
  lastMessage: string | null;  // e.g. Notification text
  tokens: TokenCounts;         // this session
  costUsd: number;             // estimated
}

export type EventKind =
  | "taskDone"
  | "needsInput"
  | "error"
  | "sessionStart"
  | "sessionEnd"
  | "promptSubmitted"
  | "toolUse"
  | "usageThreshold";

export type Priority = "high" | "medium" | "low";

export interface NyxEvent {
  id: number;
  kind: EventKind;
  priority: Priority;
  sessionId: string | null;
  contextId: string | null;
  title: string;          // short, Nyx tone (PERSONAGEM §2)
  detail: string | null;  // <= 5 lines
  createdAt: string;      // RFC3339
  read: boolean;
}

export interface TokenCounts {
  input: number;
  output: number;
  cacheWrite: number;
  cacheRead: number;
}

export type UsageRange = "session" | "today" | "week";

export interface ModelUsage {
  model: string;
  tokens: TokenCounts;
  costUsd: number;
  messages: number;
}

export interface UsageSummary {
  range: UsageRange;
  contextId: string | null;
  from: string;            // RFC3339
  to: string;              // RFC3339
  tokens: TokenCounts;
  costUsd: number;
  sessions: number;
  messages: number;
  byModel: ModelUsage[];
  ceilingUsd: number | null; // weekly ceiling (only meaningful for "week")
  percent: number | null;    // 0..100+ of ceiling
}

export interface ProjectContext {
  id: string;              // uuid-ish, generated by core when empty
  name: string;
  rootPath: string;
  instructions: string;
  color: string | null;    // token hex or null
  createdAt: string;
  // Night 2
  allowedTools: string[];  // claude --allowedTools entries, e.g. ["Read","Edit","Bash(npm test:*)"]
  references: string[];    // file paths/notes injected into every delegation prompt
  aiEnabled: boolean;      // default AI summaries/plans for this context (opt-in)
}

export type PlanPreset = "pro" | "max5x" | "max20x" | "custom";

export interface Settings {
  planPreset: PlanPreset;
  weeklyCeilingUsd: number;   // estimate; user-calibrated
  alertThresholds: number[];  // default [80, 95]
  doNotDisturb: boolean;
  dndSchedule: { start: string; end: string } | null; // "22:00".."08:00"
  autostart: boolean;         // default false
  dataDir: string;            // read-only, informative
  longTaskMinutes: number;    // default 10 — Stop after >= N min running -> medium "long task" toast
  sceneMode: "portrait" | "avatar3d"; // default "portrait" (approved direction E); avatar3d is beta
  asciiMode: "on" | "introOnly" | "off"; // avatar3d ASCII pass: always / only the opening scan / never. Default "on"
  // Voice (TTS) — docs/HANDOFF.md "TTS". Azure Neural first, Windows "Microsoft Maria" fallback.
  voiceEnabled: boolean;               // default true
  voiceEngine: "auto" | "azure" | "windows"; // auto = Azure when key+network, else Windows. Default "auto"
  voiceName: string;                   // Azure voice id, default "pt-BR-FranciscaNeural"
  voiceVolume: number;                 // 0..1, default 0.8
  voiceRate: number;                   // percent offset, default -5 (calm)
  voicePitch: number;                  // percent offset, default -5 (low-mid)
  voiceSpeakOn: VoiceSpeakOn;
  voiceMuted: boolean;                 // quick mute (tray + panel), default false
}

export interface VoiceSpeakOn {
  alerts: boolean;   // checkpoint "aprova?", needs input, error, permission block — default true
  opening: boolean;  // panel opening line — default true
  chat: boolean;     // Nyx chat replies — default true
  longTask: boolean; // long task finished + usage 80/95% — default true
}

export type SpeechKind = "alert" | "opening" | "chat" | "longTask" | "test";

export interface SpeechEvent {
  id: string;
  kind: SpeechKind;
  text: string;          // what she says (also shown as NyxLine while speaking)
  engine: "azure" | "windows";
  durationMs: number;
  envelope: number[];    // mouth openness 0..1, one value per 50 ms (drives the avatar's "aa")
}

export interface VoiceStatus {
  engineInUse: "azure" | "windows" | "none";
  azureKeyPresent: boolean;   // NYX_AZURE_SPEECH_KEY + NYX_AZURE_SPEECH_REGION set
  azureRegion: string | null;
  windowsVoice: string | null; // e.g. "Microsoft Maria"
  monthChars: number;         // Azure characters synthesized this calendar month (cache hits not counted)
  freeTierChars: number;      // 500000 (F0)
  speaking: boolean;
  lastError: string | null;
}

export interface Snapshot {
  status: "active" | "analyzing" | "alert";  // drives STATUS microtext and avatar state (idle/analyzing/alert)
  activeDelegations: number;                 // Night 2
  agents: AgentSession[];
  unreadEvents: number;
  weekUsage: UsageSummary;
  settings: Settings;
  contexts: ProjectContext[];
}

// ---- Commands (invoke names) ----
export interface Commands {
  get_snapshot: { args: Record<string, never>; result: Snapshot };
  get_events: { args: { limit: number; contextId?: string | null }; result: NyxEvent[] };
  get_usage: { args: { range: UsageRange; contextId?: string | null }; result: UsageSummary };
  list_contexts: { args: Record<string, never>; result: ProjectContext[] };
  save_context: { args: { ctx: ProjectContext }; result: ProjectContext };
  delete_context: { args: { id: string }; result: null };
  get_settings: { args: Record<string, never>; result: Settings };
  save_settings: { args: { settings: Settings }; result: Settings };
  export_usage_csv: { args: { range: UsageRange; contextId?: string | null }; result: string };
  mark_event_read: { args: { id: number }; result: null };
  // Round 2 — hooks onboarding (core wraps nyx_claude::hooks).
  get_hooks_status: { args: Record<string, never>; result: HooksStatus };
  install_hooks: { args: { dryRun: boolean }; result: HooksReport };
  uninstall_hooks: { args: { dryRun: boolean }; result: HooksReport };
  // Night 2 — delegation (docs/specs/NOITE-2.md §2)
  list_delegations: { args: { contextId?: string | null; includeFinished?: boolean }; result: Delegation[] };
  get_delegation: { args: { id: string }; result: Delegation };
  create_delegation: { args: { draft: DelegationDraft }; result: Delegation };   // status "draft"
  plan_delegation: { args: { contextId: string; goal: string }; result: string[] }; // AI opt-in; proposed steps
  start_delegation: { args: { id: string }; result: Delegation };               // runs step 1
  approve_step: { args: { id: string }; result: Delegation };                   // commit + next step (or finish)
  adjust_step: { args: { id: string; feedback: string }; result: Delegation };  // redo same step with feedback
  cancel_delegation: { args: { id: string }; result: Delegation };              // kills process, keeps worktree
  finish_delegation: { args: { id: string; merge: boolean }; result: Delegation }; // merge branch or keep it
  // Night 2 — chat (docs/specs/NOITE-2.md §4)
  get_chat: { args: { contextId: string | null; limit: number }; result: ChatMessage[] };
  send_chat: { args: { contextId: string | null; text: string }; result: ChatMessage }; // assistant reply
  clear_chat: { args: { contextId: string | null }; result: null };
  run_chat_action: { args: { messageId: number; actionId: string }; result: ChatMessage }; // user confirmed a card
  get_ai_status: { args: Record<string, never>; result: AiStatus };
  // Voice (TTS)
  get_voice_status: { args: Record<string, never>; result: VoiceStatus };
  test_voice: { args: { text?: string | null; voiceName?: string | null }; result: SpeechEvent };
  set_voice_muted: { args: { muted: boolean }; result: Settings };
  stop_speech: { args: Record<string, never>; result: null };
  /** Panel opening line (the same text the scene shows); queued as kind "opening". Returns the speech id or null if silenced. */
  speak_opening: { args: { text: string }; result: string | null };
}

// ---- Delegation ----
export type DelegationStatus =
  | "draft"        // created, not started
  | "running"      // a step is executing
  | "checkpoint"   // step finished; waiting for Approve / Adjust
  | "handoff"      // writing PASSAGEM.md / starting a fresh session (context >= 60%)
  | "blocked"      // a tool outside the context allowlist was needed — user decides
  | "failed"       // step errored (process died, is_error)
  | "done"         // last step approved
  | "cancelled";

export interface DelegationDraft {
  contextId: string;
  title: string;
  steps: string[];             // 1..N, user-written or from plan_delegation
  useAi: boolean;              // AI summary for this task (overrides context default)
  model: string | null;        // claude model for the agent; null = Claude Code default
}

export interface DelegationStep {
  index: number;               // 0-based
  prompt: string;
  status: "pending" | "running" | "checkpoint" | "approved" | "failed";
  attempts: number;            // 1 + adjustments
  report: { title: string; lines: string[]; truncated: boolean } | null; // <= 5 lines
  aiSummary: string | null;    // when AI is on
  feedback: string[];          // user adjustments, in order
  commit: string | null;       // short hash after approval
  costUsd: number;
  contextFill: number | null;  // 0..1 at end of the step
  liveActivity: string | null; // e.g. "Editando src/main.rs" while running
  startedAt: string | null;
  finishedAt: string | null;
}

export interface Delegation {
  id: string;
  contextId: string;
  title: string;
  status: DelegationStatus;
  currentStep: number;
  steps: DelegationStep[];
  worktreePath: string;
  branch: string;              // nyx/deleg-<short-id>
  baseBranch: string;
  claudeSessionId: string | null;
  handoffs: number;            // how many PASSAGEM.md hand-offs happened
  blockedReason: string | null;
  costUsd: number;
  createdAt: string;
  updatedAt: string;
}

// ---- Chat ----
export interface ChatAction {
  id: string;
  kind: "startDelegation" | "approveStep" | "adjustStep" | "installHooks" | "openPanel" | "createContext";
  label: string;               // button text, pt-BR
  args: Record<string, unknown>;
  state: "proposed" | "done" | "failed" | "dismissed";
}

export interface ChatMessage {
  id: number;
  contextId: string | null;
  role: "user" | "nyx";
  text: string;
  actions: ChatAction[];       // only on "nyx" messages
  costUsd: number;             // Nyx's own API cost for this reply
  createdAt: string;
}

export interface AiStatus {
  keyPresent: boolean;         // NYX_ANTHROPIC_API_KEY found in the environment
  model: string;               // Haiku model id used for chat/summaries/plans
  weekCostUsd: number;         // Nyx's own API spend (separate line in Usage)
}

export interface HooksStatus {
  settingsPath: string;      // ~/.claude/settings.json
  hookExe: string;           // absolute path of nyx-hook.exe the core would register
  hookExeExists: boolean;
  installed: boolean;        // every Nyx event is registered with this exe
  missingEvents: string[];   // Nyx events not registered yet
  otherHooks: number;        // hook entries that are not Nyx's (e.g. Orca) — never touched
}

export interface HooksReport {
  dryRun: boolean;
  changed: boolean;
  backupPath: string | null; // set when a real write happened
  diff: string;              // short human-readable summary of what changes (<= 15 lines)
  status: HooksStatus;       // status after the operation (or as it would be, on dry run)
}

