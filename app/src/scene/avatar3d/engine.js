// 1. Fingers never enter the keyboard: every skinned vertex of both hands above the key tops, at rest and at the peak of
//    a press, typing (lean 0) and analyzing (lean 0.3). Returns the smallest clearance in mm (negative = inside a key).
const KEY_TOP = 0.011 + 0.01; // keyboard-local y of the key-cap tops (base top + cap height)
let handVerts = null;
function buildHandVerts() { // vertices of the skin mesh weighted ≥ 0.5 to either hand subtree
  const skel = bodyMesh.skeleton, si = bodyMesh.geometry.attributes.skinIndex, sw = bodyMesh.geometry.attributes.skinWeight;
  const inSubtree = (root, b) => { for (; b; b = b.parent) if (b === root) return true; return false; };
  const hand = new Uint8Array(skel.bones.length);
  skel.bones.forEach((b, i) => { if (inSubtree(vrm.humanoid.getRawBoneNode('leftHand'), b)) hand[i] = 1; else if (inSubtree(vrm.humanoid.getRawBoneNode('rightHand'), b)) hand[i] = 2; });
  handVerts = [];
  for (let i = 0; i < si.count; i++) { let w = 0, side = 0; for (let j = 0; j < 4; j++) if (hand[si.getComponent(i, j)]) { w += sw.getComponent(i, j); side = hand[si.getComponent(i, j)]; } if (w >= 0.5) handVerts.push([i, side === 1 ? 'left' : 'right']); }
}
function checkFingerClearance({ press = 1, lean = 0, rest = 0, typing = 1, dip = press, t = clock.getElapsedTime() } = {}) {
  if (!vrm || !bodyMesh) return null;
  if (!handVerts) buildHandVerts();
  const saved = { lean: p.lean, rest: p.rest, typing: p.typing, spin: p.spin, yaw: p.yaw };
  Object.assign(p, { lean, rest, typing, spin: 0, yaw: 0 }); forcePress = press;
  applyPose(t, 0);
  vrm.humanoid.update(); rig.updateMatrixWorld(true); vrm.scene.updateMatrixWorld(true); bodyMesh.skeleton.update();
  const v = new THREE.Vector3(); let min = Infinity, worst = null;
  for (const [i, side] of handVerts) {
    bodyMesh.getVertexPosition(i, v).applyMatrix4(bodyMesh.matrixWorld); keyboard.worldToLocal(v);
    if (Math.abs(v.x) > KB.w / 2 + 0.01 || Math.abs(v.z) > KB.d / 2 + 0.01 || v.y < -0.05) continue; // not over the keyboard (hands on the lap are under the desk)
    const c = v.y - KEY_TOP;
    if (c < min) { min = c; worst = { side, x: +v.x.toFixed(3), z: +v.z.toFixed(3) }; }
  }
  Object.assign(p, saved); forcePress = null;
  return { minMm: min === Infinity ? null : +(min * 1000).toFixed(1), worst, press, lean };
}
// 2. The monitor never covers the face: project the face skin's bbox and the monitor's box corners from the default
//    camera for 3 aspects × 4 poses × 11 dolly steps of the intro; count 2-D overlaps (0 = pass) and report the gaps.
function checkMonitorOverlap() {
  if (!vrm) return null;
  let face = null; vrm.scene.traverse((o) => { if (o.isSkinnedMesh && /Face.*SKIN/i.test((Array.isArray(o.material) ? o.material[0] : o.material).name)) face = o; });
  if (!face) face = bodyMesh;
  const savedPos = camera.position.clone(), savedAspect = camera.aspect, savedP = { ...p };
  const setPose = (spin, yaw) => { Object.assign(p, { spin, yaw, lean: 0, rest: 0 }); forcePress = 0; applyPose(clock.getElapsedTime(), 0); forcePress = null; vrm.humanoid.update(); rig.updateMatrixWorld(true); vrm.scene.updateMatrixWorld(true); face.skeleton.update(); };
  const v = new THREE.Vector3();
  const bbox = (pts) => { const b = { minX: 9, maxX: -9, minY: 9, maxY: -9 }; for (const q of pts) { v.copy(q).project(camera); b.minX = Math.min(b.minX, v.x); b.maxX = Math.max(b.maxX, v.x); b.minY = Math.min(b.minY, v.y); b.maxY = Math.max(b.maxY, v.y); } return b; };
  const facePts = () => { const out = []; for (const m of [face, bodyMesh]) { if (!m) continue; const pos = m.geometry.attributes.position; for (let i = 0; i < pos.count; i += 2) out.push(m.getVertexPosition(i, new THREE.Vector3()).applyMatrix4(m.matrixWorld)); } return out; }; // face + body (torso, arms, hands)
  const monBoxes = []; monitor.traverse((o) => { if (o.isMesh && o.geometry.type === 'BoxGeometry') { const g = o.geometry.parameters, pts = []; for (const sx of [-1, 1]) for (const sy of [-1, 1]) for (const sz of [-1, 1]) pts.push(o.localToWorld(new THREE.Vector3(sx * g.width / 2, sy * g.height / 2, sz * g.depth / 2))); monBoxes.push(pts); } });
  const depth = (q) => camera.position.distanceTo(q);
  const poses = [['idle', 0, 0], ['glance', 0, 0.3], ['alert', 0.45, 0.3], ['introTurn', 0.55, 0.32]];
  let checks = 0, overlaps = 0; const gaps = {};
  for (const aspect of [420 / 232, 1.5, 1.0]) { // panel (420x232 and 380x210 share it), plus two safety aspects
    camera.aspect = aspect; camera.updateProjectionMatrix();
    let minGap = Infinity;
    for (const [name, spin, yaw] of poses) {
      setPose(spin, yaw); const fp = facePts();
      for (let k = 0; k <= 10; k++) {
        camera.position.lerpVectors(CAM_START, CAM_FINAL, k / 10); camera.lookAt(CAM_TARGET); camera.updateMatrixWorld(true); // default CAM_TARGET (camTarget may be moved for close-ups)
        checks++; let covered = 0, gap = Infinity;
        for (const pts of monBoxes) {
          const mb = bbox(pts), near = Math.min(...pts.map(depth));
          for (const q of fp) {
            v.copy(q).project(camera);
            const gx = Math.max(mb.minX - v.x, v.x - mb.maxX), gy = Math.max(mb.minY - v.y, v.y - mb.maxY), g = Math.max(gx, gy);
            if (g <= 0 && depth(q) > near) covered++; else if (depth(q) > near) gap = Math.min(gap, g);
          }
        }
        minGap = Math.min(minGap, gap);
        if (covered > 0) overlaps++;
      }
    }
    gaps[aspect.toFixed(2)] = +minGap.toFixed(3);
  }
  Object.assign(p, savedP); camera.aspect = savedAspect; camera.updateProjectionMatrix(); camera.position.copy(savedPos);
  return { checks, overlaps, minGapNDC: gaps };
}

