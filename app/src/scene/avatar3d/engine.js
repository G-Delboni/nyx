function styleNyx(vrm) {
  const look = [
    [/^Hair/, '#2a2236', '#0d0b12'],
    [/^Tops/, '#2a2433', '#0d0b12'],
    [/^(Bottoms|Shoes)/, '#1d1925', '#0d0b12'],
    [/SKIN$/, '#d9d3e2', '#857d93'],
    [/^EyeIris/, '#b58cff', '#8B5CF6'],
  ];
  vrm.scene.traverse((o) => {
    if (!o.isMesh) return;
    for (const m of (Array.isArray(o.material) ? o.material : [o.material])) {
      const rule = look.find(([re]) => re.test(m.name.replace(' (Outline)', '')));
      if (rule) { m.color?.set(rule[1]); m.shadeColorFactor?.set(rule[2]); }
      // The sample model's hair texture is brown: tinting multiplies it and it reads auburn once the
      // ASCII pass is off. Nyx's hair is black (PERSONAGEM §4): drop the texture, keep the #2A2236 sheen via rim.
      if (/hair/i.test(m.name)) {
        if ('map' in m && m.map) m.map = null;
        if ('shadeMultiplyTexture' in m && m.shadeMultiplyTexture) m.shadeMultiplyTexture = null;
        for (const k of ['matcapTexture', 'rimMultiplyTexture', 'emissiveMap']) if (k in m && m[k]) m[k] = null; // no brown sheen from the sample's textures
        if (m.emissive) m.emissive.set(0x000000);
        m.color?.set('#16121d');
        m.needsUpdate = true;
      }
      if (m.outlineColorFactor) m.outlineColorFactor.set(COLORS.bg);
      if (m.parametricRimColorFactor && !/EYE|FACE/.test(m.name)) {
        m.parametricRimColorFactor.set(/^Hair/.test(m.name) ? '#3a3346' : COLORS.primary);
        m.parametricRimFresnelPowerFactor = 5.0; // thinner violet rim (was washing the clothes)
        m.parametricRimLiftFactor = 0.02;
      }
    }
  });
}

function surfacePoint(meshes, origin, dir) {
  const ray = new THREE.Raycaster(origin, dir.clone().normalize(), 0, 3);
  const hit = ray.intersectObjects(meshes, false)[0];
  return hit ? { point: hit.point, normal: hit.face ? hit.face.normal.clone().transformDirection(hit.object.matrixWorld) : dir.clone().negate() } : null;
}

// Skinned vertex positions (current bone pose) in rig space: lets accessories be fitted to the real volume of hair/skin.
function skinnedPoints(meshes) {
  const v = new THREE.Vector3(), out = [];
  for (const m of meshes) {
    m.skeleton.update(); // bone matrices are only refreshed by the renderer; we measure before the first frame
    const pos = m.geometry.attributes.position;
    for (let i = 0; i < pos.count; i++) out.push(rig.worldToLocal(m.getVertexPosition(i, v).applyMatrix4(m.matrixWorld)).clone());
  }
  return out;
}

// Built at rest (T-pose), in world space, then attached to the raw bones so they follow the animation.
function addAccessories(vrm, standIn = true) {
  vrm.scene.updateMatrixWorld(true);
  const raw = (n) => vrm.humanoid.getRawBoneNode(n);
  const wp = (o) => o.getWorldPosition(new THREE.Vector3());
  const toWorldDir = (x, y, z) => new THREE.Vector3(x, y, z).transformDirection(rig.matrixWorld);
  const local = (v) => rig.worldToLocal(v.clone());
  const fromLocal = (x, y, z) => rig.localToWorld(new THREE.Vector3(x, y, z));
  const matName = (o) => (Array.isArray(o.material) ? o.material[0] : o.material)?.name ?? ''; // MToon meshes carry [main, outline]
  const meshes = []; vrm.scene.traverse((o) => { if (o.isMesh) meshes.push(o); });
  const byName = (re) => meshes.filter((m) => re.test(matName(m)));
  const parts = [];
  const rigQ = rig.getWorldQuaternion(new THREE.Quaternion());
  // obj is authored in rig space (Nyx faces +Z); premultiply by the rig's rotation, never `q.copy(rigQ).multiply(q)` (that squares rigQ)
  const place = (obj, worldPos, bone) => { scene.add(obj); obj.position.copy(worldPos); obj.quaternion.premultiply(rigQ); bone.attach(obj); obj.traverse((c) => c.layers.enable(NYX_LAYER)); parts.push(obj); };

  // head frame from the eye bones (generic VRM humanoid): ears sit behind and slightly below the eyes
  const eL = local(wp(raw('leftEye'))), eR = local(wp(raw('rightEye')));
  const eyeMid = eL.clone().add(eR).multiplyScalar(0.5);
  const earC = new THREE.Vector3(eyeMid.x, eyeMid.y - 0.012, eyeMid.z - 0.07); // 15 mm further forward than before (user request)

  // measure skull (face skin) and hair around the ear centre (rest pose). A real headset presses into the hair, so the
  // cups sit at the hair's 90th-percentile half width (loose side locks may cross the cup) but always outside the skull,
  // and the band lies on the hair's 80th-percentile radius per angle (the outermost strands brush over it).
  const skinned = meshes.filter((m) => m.isSkinnedMesh);
  const faceMeshes = byName(/Face.*SKIN/i).length ? byName(/Face.*SKIN/i) : skinned;
  const hairMeshes = byName(/HAIR/i).length ? byName(/HAIR/i) : skinned;
  const skullPts = skinnedPoints(faceMeshes).map((p) => p.sub(earC));
  const hairPts = skinnedPoints(hairMeshes).map((p) => p.sub(earC));
  const CUP_R = 0.042, CUP_T = 0.026, BAND_R = 0.007;
  const pct = (arr, k) => (arr.length ? arr.sort((a, b) => a - b)[Math.floor(k * (arr.length - 1))] : 0);
  const sideHair = [], NB = 24, bins = Array.from({ length: NB + 1 }, () => []); // 0 = her left ear, PI = right ear
  let skullSide = 0;
  for (const q of hairPts) {
    if (Math.abs(q.y) < CUP_R + 0.005 && Math.abs(q.z) < CUP_R + 0.005) sideHair.push(Math.abs(q.x));
    if (Math.abs(q.z) < 0.03 && q.y > -0.02) bins[Math.round(Math.atan2(Math.max(0, q.y), q.x) / Math.PI * NB)].push(Math.hypot(q.x, q.y));
  }
  for (const q of skullPts) if (Math.abs(q.y) < CUP_R && Math.abs(q.z) < CUP_R) skullSide = Math.max(skullSide, Math.abs(q.x));
  const R = Math.max(pct(sideHair, 0.9), skullSide - 0.004) + 0.002; // cup inner face (sample model: hair p90 0.104, skull incl. ears 0.109)
  const prof = bins.map((b) => pct(b, 0.8));
  for (let i = 1; i < NB; i++) prof[i] = Math.max(prof[i], (prof[i - 1] + prof[i + 1]) / 2 - 0.004); // fill thin bins
  const cupInner = R, cupX = cupInner + CUP_T / 2;

  // headphones: band lying on the hair profile, cups pressed lightly into the side hair, neon rings on the outer faces
  const phones = new THREE.Group();
  const bandPts = [];
  for (let i = 0; i <= NB; i++) {
    const a = (i / NB) * Math.PI;
    const r = Math.max(prof[i] + 0.003, cupX);
    bandPts.push(new THREE.Vector3(Math.cos(a) * r, Math.sin(a) * r, 0));
  }
  bandPts[0].set(cupX, 0, 0); bandPts[NB].set(-cupX, 0, 0); // ends disappear into the cups
  const band = new THREE.Mesh(new THREE.TubeGeometry(new THREE.CatmullRomCurve3(bandPts, false, 'catmullrom', 0.3), 40, BAND_R, 8, false), darkTech);
  phones.add(band);
  for (const s of [1, -1]) {
    const cup = new THREE.Mesh(new THREE.CylinderGeometry(CUP_R, CUP_R, CUP_T, 28), darkTech);
    cup.rotation.z = Math.PI / 2; cup.position.set(s * cupX, 0, 0);
    const ring = new THREE.Mesh(new THREE.TorusGeometry(0.03, 0.0045, 8, 40), neonMat);
    ring.rotation.y = Math.PI / 2; ring.position.set(s * (cupX + CUP_T / 2 + 0.002), 0, 0);
    phones.add(cup, ring);
  }
  // boom microphone from the lower front of her LEFT cup (+X, the side facing the camera) to just beside her mouth.
  // Mouth centre measured from the FaceMouth mesh; the path stays outside the face skin (checked per point below).
  const mouthBox = new THREE.Box3();
  for (const q of skinnedPoints(byName(/^FaceMouth/))) mouthBox.expandByPoint(q);
  if (!mouthBox.isEmpty()) {
    const mouth = mouthBox.getCenter(new THREE.Vector3()).sub(earC);          // relative to the headset origin
    const tipP = new THREE.Vector3(mouth.x + 0.024, mouth.y - 0.004, mouth.z + 0.016);
    const ctrl = [
      new THREE.Vector3(cupX, -0.022, 0.02),                                    // leaves the cup, low and forward
      new THREE.Vector3(cupX - 0.006, -0.038, 0.06),
      new THREE.Vector3(tipP.x + 0.045, tipP.y - 0.006, tipP.z - 0.03),        // sweeps along the jaw, outside the cheek
      tipP,
    ];
    // keep every control point outside the face skin by at least 12 mm (radial push from the face's centre line)
    for (const pnt of ctrl.slice(1, 3)) {
      for (const q of skullPts) { // relative to earC, like ctrl
        if (Math.abs(q.y - pnt.y) < 0.01 && Math.abs(q.z - pnt.z) < 0.01 && q.x > 0 && pnt.x < q.x + 0.012) pnt.x = q.x + 0.012;
      }
    }
    const boom = new THREE.Group();
    boom.add(new THREE.Mesh(new THREE.TubeGeometry(new THREE.CatmullRomCurve3(ctrl), 32, 0.0032, 8, false), darkTech));
    const capsule = new THREE.Mesh(new THREE.CapsuleGeometry(0.0065, 0.014, 4, 12), darkTech);
    capsule.position.copy(tipP);
    capsule.quaternion.setFromUnitVectors(new THREE.Vector3(0, 1, 0), tipP.clone().sub(ctrl[2]).normalize());
    const micLed = new THREE.Mesh(new THREE.SphereGeometry(0.0022, 8, 6), neonMat); // tiny "mic live" LED
    micLed.position.copy(tipP).add(new THREE.Vector3(0.006, 0.004, -0.004));
    boom.add(capsule, micLed);
    phones.add(boom);
  }
  place(phones, fromLocal(earC.x, earC.y, earC.z), raw('head'));

  // earring on her LEFT ear (+X): thin chain + terminal-cursor pendant that blinks, hanging from the bottom of the left cup
  const ear = new THREE.Group();
  const chain = new THREE.Mesh(new THREE.CylinderGeometry(0.0012, 0.0012, 0.03, 6), new THREE.MeshStandardMaterial({ color: '#b9b2d6', metalness: 0.9, roughness: 0.3 }));
  chain.position.y = -0.015;
  const cursor = new THREE.Mesh(new THREE.BoxGeometry(0.009, 0.024, 0.005), cursorMat);
  cursor.position.y = -0.039;
  ear.add(chain, cursor);
  place(ear, fromLocal(earC.x + cupX + CUP_T / 2 + 0.003, earC.y - CUP_R - 0.002, earC.z + 0.015), raw('head')); // from the cup's outer rim, clear of the side hair

  // Headphones, mic and earring above are fitted to ANY model (VRoid can't build them well), so the real
  // nyx.vrm keeps them. Everything below is what VRoid itself paints/models: only for the stand-in sample.
  if (!standIn) return parts;

  // mole: just below her LEFT eye, near the outer corner, snapped onto the face surface
  {
    const hit = surfacePoint(byName(/^Face_00_SKIN/), fromLocal(eL.x + 0.012, eL.y - 0.026, eL.z + 0.3), toWorldDir(0, 0, -1));
    if (hit) {
      const mole = new THREE.Mesh(new THREE.CircleGeometry(0.0033, 12), new THREE.MeshBasicMaterial({ color: '#2a2236' }));
      scene.add(mole); mole.position.copy(hit.point).addScaledVector(hit.normal, 0.0015);
      mole.lookAt(hit.point.clone().addScaledVector(hit.normal, 1));
      raw('head').attach(mole); mole.layers.enable(NYX_LAYER); parts.push(mole);
    }
  }

  // high collar around the neck (follows the upper chest so the head turns inside it).
  // Sized from the neck skin itself — not from R, which includes the hair and made a neck-brace.
  const neck = local(wp(raw('neck')));
  const collarY = neck.y + 0.025;
  let neckR = 0;
  for (const q of skinnedPoints(byName(/SKIN$/))) {
    if (Math.abs(q.y - collarY) > 0.012) continue;
    const r = Math.hypot(q.x - neck.x, q.z - neck.z);
    if (r < 0.08) neckR = Math.max(neckR, r);
  }
  neckR = neckR || 0.045;
  const collar = new THREE.Mesh(new THREE.CylinderGeometry(neckR + 0.008, neckR + 0.022, 0.075, 28, 1, true), mat('#15111c', { side: THREE.DoubleSide, roughness: 0.5 }));
  place(collar, fromLocal(neck.x, collarY, neck.z), raw('upperChest') ?? raw('chest'));

  // neon "L" strips painted into an emissive map of the top (they deform with the cloth: nothing sticks out of the chest)
  addJacketStrips(vrm, raw, byName(/^Tops/)[0]);
  // light makeup painted into the face texture + tinted eyeliner/lips
  addMakeup(vrm, raw, byName(/^Face_00_SKIN/)[0], meshes);

  // long sleeves: the arm part of the skin mesh, re-skinned with the top's MToon material and pushed 2 mm out along
  // the normals, so the sleeve follows exactly what the skin does (typing, spin, hands on the lap) with zero poke-through.
  // The wrist seam is hidden under a cuff ring (with a thin neon band) attached to the forearm bone.
  bangsReport = addBangs(vrm, { raw, place, fromLocal, byName, eyeMid, eL, eR, earC, BAND_R });
  addSleeves(vrm, raw, byName(/^Body_00_SKIN/)[0], byName(/^Tops/)[0], place, fromLocal);
  return parts;
}

// UV of the point where a ray (rig space, from `from` along `dir`) hits `mesh`, or null
function uvHit(mesh, from, dir) {
  const r = new THREE.Raycaster(rig.localToWorld(from.clone()), dir.clone().transformDirection(rig.matrixWorld).normalize(), 0, 3);
  const h = r.intersectObject(mesh, false)[0];
  return h && h.uv ? h.uv.clone() : null;
}
// Canvas texture in glTF orientation (flipY false, sRGB), optionally starting from an existing texture's image
function canvasTexture(w, h, base, draw) {
  const c = document.createElement('canvas'); c.width = w; c.height = h;
  const g = c.getContext('2d');
  if (base?.image) g.drawImage(base.image, 0, 0, w, h); else { g.fillStyle = '#000'; g.fillRect(0, 0, w, h); }
  draw(g, w, h);
  const t = new THREE.CanvasTexture(c);
  t.flipY = false; t.colorSpace = THREE.SRGBColorSpace;
  return t;
}

let jacketMat = null; // MToon of the top: its emissive colour follows "glow"
function addJacketStrips(vrm, raw, tops) {
  if (!tops) return;
  const matT = Array.isArray(tops.material) ? tops.material[0] : tops.material;
  const chest = rig.worldToLocal(raw('upperChest').getWorldPosition(new THREE.Vector3()));
  const fwd = new THREE.Vector3(0, 0, -1), down = new THREE.Vector3(0, -1, 0);
  const W = 512, H = 1024, STRIP = 0.008; // strip width in metres
  const segs = []; // [uvA, uvB, widthPx]
  for (const s of [1, -1]) {
    // "L" on the upper chest: bar from 9 cm to 2 cm above the upper-chest bone, foot 3.5 cm toward the shoulder
    const top = uvHit(tops, new THREE.Vector3(s * 0.075, chest.y + 0.09, chest.z + 0.5), fwd);
    const bot = uvHit(tops, new THREE.Vector3(s * 0.075, chest.y + 0.02, chest.z + 0.5), fwd);
    const foot = uvHit(tops, new THREE.Vector3(s * 0.11, chest.y + 0.02, chest.z + 0.5), fwd);
    if (top && bot && foot) {
      const uScale = Math.abs(foot.x - bot.x) / 0.035, vScale = Math.abs(top.y - bot.y) / 0.07; // UV units per metre (anisotropic atlas)
      segs.push([top, bot, STRIP * uScale * W], [bot, foot, STRIP * vScale * H]);
      // short bar on the shoulder (ref-01), ray from above
      const sh1 = uvHit(tops, new THREE.Vector3(s * 0.085, chest.y + 0.3, chest.z - 0.01), down);
      const sh2 = uvHit(tops, new THREE.Vector3(s * 0.13, chest.y + 0.3, chest.z - 0.01), down);
      if (sh1 && sh2) segs.push([sh1, sh2, STRIP * vScale * H]);
    }
  }
  if (!segs.length) return;
  const tex = canvasTexture(W, H, null, (g) => {
    g.strokeStyle = '#ffffff'; g.lineCap = 'butt';
    for (const [a, b, lw] of segs) { g.lineWidth = Math.max(2, lw); g.beginPath(); g.moveTo(a.x * W, a.y * H); g.lineTo(b.x * W, b.y * H); g.stroke(); }
  });
  matT.emissiveMap = tex; matT.emissive.set(COLORS.neon); matT.needsUpdate = true;
  jacketMat = matT;
}

function addMakeup(vrm, raw, face, meshes) {
  if (!face) return;
  const matF = Array.isArray(face.material) ? face.material[0] : face.material;
  if (!matF.map?.image) return;
  const fwd = new THREE.Vector3(0, 0, -1);
  const W = matF.map.image.width || 1024, H = matF.map.image.height || 1024;
  const eyes = [];
  for (const s of [1, -1]) {
    const e = rig.worldToLocal(raw(s > 0 ? 'leftEye' : 'rightEye').getWorldPosition(new THREE.Vector3()));
    // the skin has a hole where the eye meshes sit (at rest, no blink), so the outer-corner probe tries a few spots
    const probe = (...offsets) => { for (const [dx, dy] of offsets) { const h = uvHit(face, new THREE.Vector3(e.x + dx, e.y + dy, e.z + 0.3), fwd); if (h) return h; } return null; };
    const c = probe([0, 0]), up = probe([0, 0.018]), out = probe([s * 0.022, 0.004], [s * 0.025, 0.007], [s * 0.028, 0.01]), wing = probe([s * 0.031, 0.011]), cheek = probe([s * 0.014, -0.04]);
    if (c && up && out && wing && cheek) eyes.push({ s, c, up, out, wing, cheek, uPerM: Math.abs(wing.x - c.x) / 0.031, vPerM: Math.abs(up.y - c.y) / 0.018 });
  }
  if (!eyes.length) return;
  matF.map = canvasTexture(W, H, matF.map, (g) => {
    for (const { c, up, out, wing, cheek, uPerM, vPerM } of eyes) {
      // soft violet eyeshadow on the upper lid (centred 11 mm above the eye centre, 13 × 5 mm)
      const lid = { x: c.x + (up.x - c.x) * (11 / 18), y: c.y + (up.y - c.y) * (11 / 18) };
      // heavier look (user: "maquiagem um pouco mais pesada"): two-tone smoky lid — wide violet wash + darker plum
      // crease toward the outer corner — stronger blush and a longer, thicker wing. Still the palette tokens only.
      // (review: 15 mm half-width made the two washes meet over the nose bridge = one violet mask; 12 mm, nudged 2 mm
      // outward, keeps the inner corners clean and the weight on the outer lid)
      // user (round 5): "ainda está leve" → smoky, soft-goth: violet wash + deep #2A2236 gradient on the outer corner,
      // a liner band along the upper lash line, a smudged lower-lid line and a thick wing. Washes stay 12 mm wide
      // (they must not meet over the nose bridge).
      const s = Math.sign(out.x - c.x);                       // UV direction toward the outer corner
      const U = (dx) => dx * uPerM, V = (dy) => -dy * vPerM;  // metres → UV (v grows downward)
      const lidC = { x: lid.x + s * U(0.002), y: lid.y };
      g.save(); g.globalAlpha = 0.6; g.fillStyle = COLORS.primary; g.filter = 'blur(7px)';
      g.beginPath(); g.ellipse(lidC.x * W, lidC.y * H, U(0.012) * W, 0.0065 * vPerM * H, 0, 0, Math.PI * 2); g.fill(); g.restore();
      // deep outer-corner gradient (#2A2236), smoky
      const oc = { x: out.x + s * U(0.003), y: out.y + V(0.007) }, ro = U(0.015) * W;
      const smoke = g.createRadialGradient(oc.x * W, oc.y * H, 0, oc.x * W, oc.y * H, ro);
      smoke.addColorStop(0, 'rgba(42,34,54,0.75)'); smoke.addColorStop(0.55, 'rgba(42,34,54,0.4)'); smoke.addColorStop(1, 'rgba(42,34,54,0)');
      g.fillStyle = smoke; g.fillRect(oc.x * W - ro, oc.y * H - ro, 2 * ro, 2 * ro);
      const crease = { x: lid.x + (out.x - c.x) * 0.45, y: lid.y + (up.y - c.y) * 0.1 };
      g.save(); g.globalAlpha = 0.55; g.fillStyle = '#2A2236'; g.filter = 'blur(5px)';
      g.beginPath(); g.ellipse(crease.x * W, crease.y * H, U(0.011) * W, 0.0055 * vPerM * H, 0, 0, Math.PI * 2); g.fill(); g.restore();
      // cold blush under the outer eye
      const r = 0.024 * uPerM * W;
      const grad = g.createRadialGradient(cheek.x * W, cheek.y * H, 0, cheek.x * W, cheek.y * H, r);
      grad.addColorStop(0, 'rgba(139,92,246,0.24)'); grad.addColorStop(1, 'rgba(139,92,246,0)');
      g.fillStyle = grad; g.fillRect(cheek.x * W - r, cheek.y * H - r, 2 * r, 2 * r);
      // liner band along the outer two thirds of the upper lash line, 2.4 mm, thickening the model's own lash layer
      // (review: started 16 mm inward it reached the nose bridge and the two bands joined into one dark line)
      g.save(); g.strokeStyle = 'rgba(13,11,18,0.9)'; g.lineCap = 'round'; g.lineWidth = Math.max(2, 0.0024 * vPerM * H);
      g.beginPath(); g.moveTo((c.x - s * U(0.005)) * W, (c.y + V(0.009)) * H); g.quadraticCurveTo((c.x + s * U(0.009)) * W, (c.y + V(0.012)) * H, out.x * W, (out.y + V(0.001)) * H); g.stroke();
      // smudged lower-lid line on the outer third
      g.strokeStyle = 'rgba(42,34,54,0.6)'; g.lineWidth = Math.max(1.5, 0.0016 * vPerM * H); g.filter = 'blur(2px)';
      g.beginPath(); g.moveTo((c.x + s * U(0.007)) * W, (c.y + V(-0.011)) * H); g.lineTo((out.x - s * U(0.001)) * W, (out.y + V(-0.004)) * H); g.stroke(); g.restore();
      // eyeliner wing: tapered stroke from the outer corner, 4.4 mm at the root, 40% longer than the probe point
      const hw = 0.0022 * vPerM * H;
      const tip = { x: out.x + (wing.x - out.x) * 1.4, y: out.y + (wing.y - out.y) * 1.4 };
      g.fillStyle = 'rgba(13,11,18,0.96)'; g.beginPath();
      g.moveTo(out.x * W, out.y * H - hw); g.lineTo(tip.x * W, tip.y * H); g.lineTo(out.x * W, out.y * H + hw); g.closePath(); g.fill();
    }
  });
  matF.needsUpdate = true;
  // tint the separate eyeliner and mouth layers: near-black liner; dark, defined plum lips
  for (const o of meshes) for (const m of (Array.isArray(o.material) ? o.material : [o.material])) {
    if (/^FaceEyeline/.test(m.name)) { m.color?.set('#0d0b12'); m.shadeColorFactor?.set('#0d0b12'); }
    if (/^FaceMouth/.test(m.name)) { m.color?.set('#5c3d73'); m.shadeColorFactor?.set('#2f2240'); }
  }
}

// One-sided half-smile: a new morph target made from the model's symmetric "happy" mouth deltas, kept only on her LEFT
// mouth corner (+X in model space, blended over 12 mm across the centre) and only in the mouth region (vertices the "aa"
// viseme moves, +1 cm). Driven directly through morphTargetInfluences (not a VRM expression), so vrm.update() leaves it.
function addSmirkMorph(vrm) {
  const targets = [];
  vrm.scene.traverse((o) => {
    if (!o.isMesh || !o.morphTargetDictionary) return;
    const geo = o.geometry, hi = o.morphTargetDictionary.happy, ai = o.morphTargetDictionary.aa;
    if (hi === undefined || ai === undefined || !geo.morphAttributes.position) return;
    const happy = geo.morphAttributes.position[hi], aa = geo.morphAttributes.position[ai], pos = geo.attributes.position;
    // mouth level = mean y of the vertices the "aa" viseme moves (lips); keep deltas within 28 mm of it, so the
    // "happy" eye squint (≈70 mm higher) is left out. Side: her RIGHT corner (-X) — the mic capsule sits by the left one.
    let sumY = 0, nY = 0;
    for (let i = 0; i < aa.count; i++) if (Math.abs(aa.getX(i)) + Math.abs(aa.getY(i)) + Math.abs(aa.getZ(i)) > 1e-6) { sumY += pos.getY(i); nY++; }
    if (!nY) return;
    const mouthY = sumY / nY;
    const w = new Float32Array(pos.count);
    let any = false;
    for (let i = 0; i < pos.count; i++) {
      if (Math.abs(pos.getY(i) - mouthY) > 0.028) continue;
      w[i] = Math.min(1, Math.max(0, (-pos.getX(i) + 0.004) / 0.012));
      if (w[i] > 0) any = true;
    }
    if (!any) return;
    const weighted = (src) => { const a = new Float32Array(src.count * 3); for (let i = 0; i < src.count; i++) { a[i * 3] = src.getX(i) * w[i]; a[i * 3 + 1] = src.getY(i) * w[i]; a[i * 3 + 2] = src.getZ(i) * w[i]; } return new THREE.Float32BufferAttribute(a, 3); };
    geo.morphAttributes.position.push(weighted(happy));
    if (geo.morphAttributes.normal?.[hi]) geo.morphAttributes.normal.push(weighted(geo.morphAttributes.normal[hi]));
    const idx = geo.morphAttributes.position.length - 1;
    o.morphTargetInfluences.push(0);
    o.morphTargetDictionary.smirk = idx;
    targets.push({ mesh: o, idx });
  });
  return targets;
}

// PERSONAGEM §4: heavy, straight bangs down to the eye line, built as a shell of (NA+1)x(NY+1) vertices in rig space.
// Columns = angle around the head's vertical axis (0 = her front, +/-A_MAX at the temples), rows = height from the hem
// (upper-lid line) up to just under the crown hair. For each vertex a ray from the skull axis measures the face skin
// (the skull) and the sample's own hair separately: across the forehead the shell rides a few mm outside the OUTERMOST
// surface (so the sample's parted fringe can't poke through); where the hair is a side lock (> 18 mm thick) the shell
// sinks INTO the lock (skull + 10 mm) so the fringe fuses into the side locks instead of wrapping the temples like a
// visor — that wrap was the dark wedge over half the face during the chair spin. The hem row curls back toward the
// brow (a lip, not a sheet edge), the top row tucks under the crown hair, and past the eye corners the hem rises into
// the hairline. Never closer than 2 mm to the skull; clearance to the headphone band is reported in mm.
function addBangs(vrm, h) {
  const { raw, place, fromLocal, byName, eyeMid, eL, eR, earC, BAND_R } = h;
  const faceM = byName(/^Face_00_SKIN/), hairM = byName(/HAIR/);
  const hairMain = hairM[0];
  if (!hairMain || !faceM.length) return null;
  const C = new THREE.Vector3(eyeMid.x, eyeMid.y + 0.02, eyeMid.z - 0.07); // skull axis (same x/z as the ear centre)
  const yBot = eyeMid.y + 0.013, yTop = eyeMid.y + 0.095;                   // upper-lid line -> under the crown hair
  const NA = 32, NY = 8, A_MAX = 0.8;                                         // +/-46 degrees: past the eye corners, into the temples
  const LOCK_MIN = 0.018;                                                     // hair thicker than this is a side lock, not the fringe layer
  const ray = new THREE.Raycaster(); ray.far = 0.5;
  const toW = (v) => rig.localToWorld(v.clone()), toDirW = (v) => v.clone().transformDirection(rig.matrixWorld);
  const hits = (set, o, d) => { ray.set(toW(o), toDirW(d)); return ray.intersectObjects(set, false); };
  const smooth = (x) => x * x * (3 - 2 * x);
  const skull = [], radius = [], ys = [], dirs = [];
  for (let i = 0; i <= NA; i++) {
    const th = -A_MAX + (2 * A_MAX * i) / NA, dir = new THREE.Vector3(Math.sin(th), 0, Math.cos(th));
    const edge = Math.min(1, Math.abs(th) / A_MAX);                       // 0 at the front, 1 at the temples
    const teeth = 0.0035 * (1 - smooth(edge)) * (1 - Math.abs(((i * 9) / NA) % 2 - 1) * 2); // light saw-tooth, 9 teeth, fading at the sides
    const hem = yBot + teeth + 0.028 * smooth(Math.max(0, (edge - 0.5) * 2)); // straight past the eye corners, then up into the hairline
    let lastSkull = 0.08;
    for (let j = 0; j <= NY; j++) {
      const y = hem + ((yTop - hem) * j) / NY, o = new THREE.Vector3(C.x, y, C.z);
      const fh = hits(faceM, o, dir), hh = hits(hairM, o, dir);
      const sk = fh.length ? fh[fh.length - 1].distance : hh.length ? hh[0].distance : lastSkull; // skin, else the hair's inner face (scalp)
      const hairOut = hh.length ? hh[hh.length - 1].distance : null;
      const r = hairOut == null ? sk : hairOut - sk > LOCK_MIN ? sk + 0.01 : hairOut; // bare brow / inside a side lock / on the fringe layer
      lastSkull = sk;
      skull.push(sk); radius.push(r); ys.push(y); dirs.push(dir);
    }
  }
  // soften the step between columns where a lock begins (the skull floor below keeps this out of the face)
  const sm = radius.slice();
  for (let i = 1; i < NA; i++) for (let j = 0; j <= NY; j++) {
    const k = i * (NY + 1) + j;
    sm[k] = (radius[k - NY - 1] + 2 * radius[k] + radius[k + NY + 1]) / 4;
  }
  const pos = [], uv = [], idx = []; let minBandClear = Infinity, minLid = Infinity, minSkull = Infinity;
  for (let i = 0; i <= NA; i++) {
    const th = -A_MAX + (2 * A_MAX * i) / NA, edge = Math.min(1, Math.abs(th) / A_MAX);
    for (let j = 0; j <= NY; j++) {
      const k = i * (NY + 1) + j;
      // proud of the measured surface: a 2 mm lip at the hem, 4.5 mm over the forehead, tucked 3 mm under the hair at
      // the top; reduced toward the temples, where the shell is already inside the lock
      let proud = j === 0 ? 0.002 : j === NY ? -0.003 : j === NY - 1 ? 0.001 : 0.0045;
      proud *= 1 - 0.6 * smooth(edge);
      // vertical strand relief (+/-0.8 mm every other column, fading at the temples and at the tucked top): the toon
      // terminator and the rim catch it, so the shell shades like combed hair instead of a smooth dome
      if (j > 0 && j < NY - 1) proud += 0.0008 * Math.sin(i * 2.4) * (1 - smooth(edge));
      const r = Math.max(sm[k] + proud, skull[k] + 0.002);
      const v = new THREE.Vector3(C.x, ys[k], C.z).addScaledVector(dirs[k], r);
      pos.push(v.x, v.y, v.z); uv.push(i / NA, j / NY);
      minSkull = Math.min(minSkull, r - skull[k]);
      minBandClear = Math.min(minBandClear, v.z - earC.z - BAND_R);
      if (j === 0) minLid = Math.min(minLid, v.y - eyeMid.y);
    }
  }
  for (let i = 0; i < NA; i++) for (let j = 0; j < NY; j++) {
    const a = i * (NY + 1) + j, b = a + NY + 1;
    idx.push(a, b, a + 1, b, b + 1, a + 1);
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('uv', new THREE.Float32BufferAttribute(uv, 2));
  g.setIndex(idx); g.computeVertexNormals();

  // Material: the hair's MToon, but it has to read as hair and not as a black block (a flat shell has no strands and
  // no outline). A small strand texture (vertical streaks in the #16121D..#2A2236 range, one soft sheen band a third of
  // the way down, darker toward the hem) multiplies both the lit and the shade colour, the toon step is softened, the
  // lit side is pushed a bit further round the head, and the rim stays the hair's #3A3346.
  const hairMat = Array.isArray(hairMain.material) ? hairMain.material[0] : hairMain.material;
  const matB = hairMat.clone(); matB.name = 'Bangs'; matB.side = THREE.DoubleSide;
  const strands = canvasTexture(128, 64, null, (ctx, w, hh) => {
    const rnd = mulberry32(7);
    // the scene's lights are dim (hemisphere 0.7 + fill 0.3): on screen these land near the hair's #16121D..#2A2236
    ctx.fillStyle = '#241d30'; ctx.fillRect(0, 0, w, hh);
    for (let x = 0; x < w; x++) { // u across the fringe: one streak per texel column, a few lighter strands
      const k = rnd();
      ctx.fillStyle = k < 0.25 ? '#181321' : k < 0.4 ? '#2d2539' : k < 0.46 ? '#352d48' : '#241d30';
      ctx.fillRect(x, 0, 1, hh);
    }
    const band = ctx.createLinearGradient(0, hh * 0.52, 0, hh * 0.78); // v = 0 is the hem (bottom of the fringe)
    band.addColorStop(0, 'rgba(78,68,104,0)'); band.addColorStop(0.5, 'rgba(78,68,104,0.6)'); band.addColorStop(1, 'rgba(78,68,104,0)');
    ctx.fillStyle = band; ctx.fillRect(0, 0, w, hh);
    const hemShade = ctx.createLinearGradient(0, 0, 0, hh * 0.3); // the ends sit in the brow's shadow
    hemShade.addColorStop(0, 'rgba(13,11,18,0.6)'); hemShade.addColorStop(1, 'rgba(13,11,18,0)');
    ctx.fillStyle = hemShade; ctx.fillRect(0, 0, w, hh);
  });
  strands.wrapS = strands.wrapT = THREE.ClampToEdgeWrapping;
  matB.map = strands; matB.color.set('#ffffff');
  if ('shadeMultiplyTexture' in matB) { matB.shadeMultiplyTexture = strands; matB.shadeColorFactor.set('#8c84a0'); }
  if ('shadeToonyFactor' in matB) matB.shadeToonyFactor = 0.55;   // softer terminator than the sample's hard toon step
  if ('shadingShiftFactor' in matB) matB.shadingShiftFactor = -0.25; // more of the shell counts as lit
  matB.needsUpdate = true;
  const bangs = new THREE.Mesh(g, matB); bangs.name = 'bangs';
  place(bangs, fromLocal(0, 0, 0), raw('head'));
  return { vertices: pos.length / 3, hemAboveEyeMm: +(minLid * 1000).toFixed(1), bandClearanceMm: +(minBandClear * 1000).toFixed(1), skullClearanceMm: +(minSkull * 1000).toFixed(1), spanDeg: Math.round((A_MAX * 2 * 180) / Math.PI) };
}

function addSleeves(vrm, raw, body, tops, place, fromLocal) {
  if (!body || !tops) return;
  const skel = body.skeleton, geo = body.geometry;
  const inSubtree = (root, bone) => { for (let b = bone; b; b = b.parent) if (b === root) return true; return false; };
  const armBone = new Uint8Array(skel.bones.length); // 1 = left arm, 2 = right arm (upper arm subtree minus the hand subtree)
  skel.bones.forEach((b, i) => { for (const [side, id] of [['left', 1], ['right', 2]]) if (inSubtree(raw(`${side}UpperArm`), b) && !inSubtree(raw(`${side}Hand`), b)) armBone[i] = id; });
  const si = geo.attributes.skinIndex, sw = geo.attributes.skinWeight, pos = geo.attributes.position, nor = geo.attributes.normal;
  const armW = new Float32Array(pos.count);
  for (let i = 0; i < pos.count; i++) for (let j = 0; j < 4; j++) if (armBone[si.getComponent(i, j)]) armW[i] += sw.getComponent(i, j);
  const src = geo.index ? geo.index.array : Array.from({ length: pos.count }, (_, i) => i), idx = [];
  for (let t = 0; t < src.length; t += 3) if (armW[src[t]] >= 0.5 && armW[src[t + 1]] >= 0.5 && armW[src[t + 2]] >= 0.5) idx.push(src[t], src[t + 1], src[t + 2]);
  if (!idx.length) return;
  const p2 = pos.array.slice();
  for (let i = 0; i < pos.count; i++) if (armW[i] > 0) for (let k = 0; k < 3; k++) p2[i * 3 + k] += nor.array[i * 3 + k] * 0.002;
  const sg = new THREE.BufferGeometry();
  sg.setAttribute('position', new THREE.BufferAttribute(p2, 3));
  for (const a of ['normal', 'uv', 'skinIndex', 'skinWeight']) if (geo.attributes[a]) sg.setAttribute(a, geo.attributes[a]);
  sg.setIndex(idx);
  const sleeveMat = (Array.isArray(tops.material) ? tops.material[0] : tops.material).clone(); // same MToon look as the top (colour, shade, rim)
  sleeveMat.map = null; sleeveMat.shadeMultiplyTexture = null; sleeveMat.emissiveMap = null; sleeveMat.emissive.set(0x000000);
  sleeveMat.name = 'Sleeves'; sleeveMat.needsUpdate = true;
  vrm.materials?.push(sleeveMat); // so vrm.update() keeps its MToon uniforms in sync like the model's own materials
  const sleeves = new THREE.SkinnedMesh(sg, sleeveMat);
  sleeves.bindMode = body.bindMode;
  sleeves.bind(skel, body.bindMatrix);
  body.parent.add(sleeves);
  sleeves.position.copy(body.position); sleeves.quaternion.copy(body.quaternion); sleeves.scale.copy(body.scale);
  sleeves.frustumCulled = false; sleeves.layers.enable(NYX_LAYER);

  // cuffs at the wrists: measured from the forearm skin, attached to the lower-arm bone
  const pts = skinnedPoints([body]);
  for (const side of ['left', 'right']) {
    const elbow = rig.worldToLocal(raw(`${side}LowerArm`).getWorldPosition(new THREE.Vector3()));
    const wrist = rig.worldToLocal(raw(`${side}Hand`).getWorldPosition(new THREE.Vector3()));
    const dir = wrist.clone().sub(elbow).normalize();
    let rW = 0.02;
    const d = new THREE.Vector3();
    for (let i = 0; i < pts.length; i++) {
      if (armW[i] < 0.5) continue;
      d.copy(pts[i]).sub(wrist); const along = d.dot(dir);
      if (along > -0.035 && along < 0.005) rW = Math.max(rW, d.addScaledVector(dir, -along).length());
    }
    const cuff = new THREE.Group();
    cuff.add(new THREE.Mesh(new THREE.CylinderGeometry(rW + 0.006, rW + 0.005, 0.03, 20), sleeveMat));
    const neon = new THREE.Mesh(new THREE.TorusGeometry(rW + 0.0065, 0.002, 6, 28), neonMat); // thin neon band on the cuff (ref-02)
    neon.rotation.x = Math.PI / 2; neon.position.y = 0.01;
    cuff.add(neon);
    cuff.quaternion.setFromUnitVectors(new THREE.Vector3(0, 1, 0), dir.clone().negate()); // local +y points toward the elbow
    const c = wrist.clone().addScaledVector(dir, -0.012);
    place(cuff, fromLocal(c.x, c.y, c.z), raw(`${side}LowerArm`));
  }
}

