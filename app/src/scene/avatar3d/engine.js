// ---------- post-processing: ASCII pass ----------
function makeGlyphTexture() {
  const cw = 32, ch = 48, n = GLYPHS.length;
  const c = document.createElement('canvas'); c.width = cw * n; c.height = ch;
  const g = c.getContext('2d');
  g.fillStyle = '#000'; g.fillRect(0, 0, c.width, c.height);
  g.fillStyle = '#fff'; g.font = 'bold 40px JetBrains Mono, monospace'; g.textAlign = 'center'; g.textBaseline = 'middle';
  for (let i = 0; i < n; i++) g.fillText(GLYPHS[i], i * cw + cw / 2, ch / 2 + 2);
  const t = new THREE.CanvasTexture(c);
  t.minFilter = THREE.LinearFilter; t.magFilter = THREE.LinearFilter; t.generateMipmaps = false;
  return t;
}
const maskTarget = new THREE.WebGLRenderTarget(1, 1);
const maskMaterial = new THREE.MeshBasicMaterial({ color: 0xffffff });
const AsciiShader = {
  uniforms: {
    tDiffuse: { value: null }, tMask: { value: null }, tGlyph: { value: null },
    uRes: { value: new THREE.Vector2() }, uCell: { value: new THREE.Vector2(7, 12) }, uN: { value: GLYPHS.length },
    uAll: { value: 0 }, uBg: { value: 0 }, uSweep: { value: -1 }, uGlitch: { value: 0 }, uTime: { value: 0 }, uFade: { value: 1 },
    cBg: { value: new THREE.Color(COLORS.bg) }, cA: { value: new THREE.Color(COLORS.primary) }, cB: { value: new THREE.Color(COLORS.neon) },
  },
  vertexShader: /* glsl */`varying vec2 vUv; void main(){ vUv = uv; gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0); }`,
  fragmentShader: /* glsl */`
    uniform sampler2D tDiffuse, tMask, tGlyph;
    uniform vec2 uRes, uCell; uniform float uN, uAll, uBg, uSweep, uGlitch, uTime, uFade;
    uniform vec3 cBg, cA, cB;
    varying vec2 vUv;
    float hash(float n){ return fract(sin(n) * 43758.5453); }
    void main(){
      vec2 uv = vUv;
      float row = floor(uv.y * uRes.y / uCell.y);
      float tick = floor(uTime * 30.0);
      float gl = uGlitch * step(0.55, hash(row + tick));
      uv.x += gl * (hash(row * 1.7 + tick) - 0.5) * 0.08;
      vec3 src = texture2D(tDiffuse, uv).rgb;
      vec2 px = uv * uRes;
      vec2 cellUv = (floor(px / uCell) + 0.5) * uCell / uRes;
      vec2 f = fract(px / uCell);
      vec3 cs = texture2D(tDiffuse, cellUv).rgb;
      float lum = dot(cs, vec3(0.2126, 0.7152, 0.0722));
      lum = pow(clamp(lum * 2.2, 0.0, 1.0), 0.4545);
      float idx = floor(lum * (uN - 1.0) + 0.5);
      float g = texture2D(tGlyph, vec2((idx + f.x) / uN, f.y)).r;
      vec3 asc = mix(cBg, mix(cA, cB, lum), g);
      float m = texture2D(tMask, cellUv).r;
      float a = max(uAll, uBg * (1.0 - m));
      if (uSweep >= 0.0) a = max(a, 1.0 - smoothstep(uSweep - 0.03, uSweep + 0.03, uv.y));
      a = max(a, gl);
      vec3 col = mix(src, asc, clamp(a, 0.0, 1.0));
      if (uSweep >= 0.0) col += cB * exp(-abs(uv.y - uSweep) * 160.0) * 0.8;
      gl_FragColor = vec4(col * uFade, 1.0);
    }`,
};
