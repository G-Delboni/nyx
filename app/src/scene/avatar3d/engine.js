const p = {
  spin: 0, rest: 0, yaw: 0, lean: 0, typing: 0, tapRate: 4, surprised: 0, smirk: 0, glow: 1,
  bg: 0.28, all: 0, sweep: -1, glitch: 0, fade: 1, nod: 0,
};
const tweens = [];
function go(key, to, ms = DUR.std, ease = EASE.std, delay = 0) {
  for (let i = tweens.length - 1; i >= 0; i--) if (tweens[i].key === key) tweens.splice(i, 1);
  tweens.push({ key, from: null, to, ms, ease, t: -delay });
}
function updateTweens(dtMs) {
  for (let i = tweens.length - 1; i >= 0; i--) {
    const tw = tweens[i];
    tw.t += dtMs;
    if (tw.t < 0) continue;
    if (tw.from === null) tw.from = p[tw.key];
    const k = Math.min(1, tw.t / tw.ms);
    p[tw.key] = tw.from + (tw.to - tw.from) * tw.ease(k);
    if (k >= 1) tweens.splice(i, 1);
  }
}
let timeline = [];
function at(ms, fn) { timeline.push({ at: ms, fn }); }

// ---------- state machine ----------
const STATE_FPS = { intro: 60, idle: 30, analyzing: 30, alert: 30 };
if (opts.reducedMotion) Object.assign(STATE_FPS, { intro: 30, idle: 15, analyzing: 15, alert: 15 });
const ASCII = opts.asciiMode ?? 'on';
let state = 'idle', stateTime = 0, hidden = false, hiding = 0, bgAsciiOn = ASCII === 'on', idleBeat = 0;
if (ASCII === 'off') asciiPass.enabled = false; // composer skips the pass; p.bg stays 0 so the mask is never rendered
const BG = () => (bgAsciiOn ? 0.28 : 0);

function backToDesk(delay = 0) {
  // chair returns first, then the hands go back to the keyboard (stagger 150 ms)
  go('spin', 0, DUR.slow, EASE.std, delay);
  go('yaw', 0, DUR.std, EASE.std, delay);
  go('rest', 0, DUR.std, EASE.std, delay + 150);
  go('surprised', 0, DUR.std, EASE.std, delay);
}

function setState(s) {
  state = s; stateTime = 0; timeline = []; idleBeat = 0;
  tweens.length = 0; // new state takes over from the current values (no stale intro sweeps)
  if (s !== 'intro') { p.all = 0; p.fade = 1; p.sweep = -1; camera.position.copy(CAM_FINAL); }

  if (s === 'intro') {
    Object.assign(p, { all: 1, fade: 0, sweep: 1, spin: 0, rest: 0, yaw: 0, typing: 1, tapRate: 7, glow: 0, bg: BG() });
    if (ASCII === 'off') Object.assign(p, { all: 0, fade: 1, sweep: -1 }); // no ASCII birth: the scene just fades in with the lights
    camera.position.copy(CAM_START);
    go('fade', 1, 400, EASE.out);
    if (ASCII !== 'off') {
      at(300, () => { p.all = 0; go('sweep', -0.06, 1000, EASE.sine); });
      at(1300, () => { p.sweep = -1; });
    }
    at(1400, () => { go('typing', 0, DUR.quick); go('spin', -0.07, 150, EASE.std); go('lean', 0.08, 150); });   // anticipation
    at(1550, () => { go('spin', 0.55, DUR.slow, EASE.std); go('rest', 1, DUR.std); go('lean', 0, DUR.std); }); // the turn
    at(1450, () => go('yaw', 0.32, DUR.std, EASE.std));                                                       // head leads the body
    at(2050, () => { go('glow', 1, 300, EASE.out); go('smirk', 1, DUR.slow); });
    at(3300, () => { setState('idle'); if (opts.onIntroEnd) opts.onIntroEnd(); });
  } else if (s === 'idle') {
    backToDesk();
    go('typing', 1, DUR.std, EASE.std, 500); go('tapRate', 4.5, DUR.std); go('lean', 0, DUR.std);
    go('smirk', 0, DUR.slow); go('bg', BG(), DUR.slow); go('glow', 1, DUR.std);
  } else if (s === 'analyzing') {
    backToDesk();
    go('typing', 1, DUR.std, EASE.std, 300); go('tapRate', 11, DUR.std); go('lean', 0.3, DUR.slow);
    go('smirk', 0, DUR.std); go('bg', bgAsciiOn ? 0.45 : 0, DUR.slow);
  } else if (s === 'alert') {
    // urgency: quick reaction (180 ms, decelerate), no overshoot; glitch pulse on entry
    if (ASCII === 'on') { p.glitch = 1; at(150, () => go('glitch', 0, 120, EASE.in)); } // otherwise only the neon pulse
    go('typing', 0, 120); go('yaw', 0.3, DUR.quick, EASE.out); go('surprised', 1, DUR.quick, EASE.out);
    go('spin', 0.45, DUR.std, EASE.std, 80); go('rest', 1, DUR.std, EASE.std, 60); go('lean', 0, DUR.quick);
    at(900, () => go('surprised', 0.35, DUR.slow));
  }
}

// ---------- speech: mouth driven by the TTS amplitude envelope (one value per 50 ms, 0..1) ----------
// The core emits nyx://speech when the audio starts; Avatar3d forwards the envelope with its start time (setSpeech).
// Nothing is faked any more: muted, her lips stay closed while the line types in the HUD.
const SPEECH = {
  stepMs: 50,
  maxAa: 0.42,   // calm speaker: discreet opening (the model's full "aa" is a shout)
  maxOh: 0.14,   // a little rounding on the louder swells so the lips do not flap one shape
  attack: 22,    // damp lambda: lips open on the syllable (~45 ms to 63%)
  release: 11,   // ...and close softer (~90 ms), no tremble between samples
  gazeLift: 0.05, // rad: while typing she lifts her eyes a little off the screen when she speaks (talks to you)
};
let speech = null;                       // { env: number[], startedAt: performance.now() base }
let mouth = 0, mouthOh = 0, gazeUp = 0;  // smoothed channels
function setSpeech(envelope, startedAtMs = performance.now()) {
  speech = envelope && envelope.length ? { env: envelope, startedAt: startedAtMs } : null;
}
function envelopeNow(now) {
  if (!speech) return 0;
  const x = (now - speech.startedAt) / SPEECH.stepMs;
  if (x < 0) return 0;
  const i = Math.floor(x), e = speech.env;
  if (i >= e.length) { speech = null; return 0; } // past the end (speech-end may arrive a frame late)
  const a = e[i], b = i + 1 < e.length ? e[i + 1] : 0;
  return a + (b - a) * (x - i);                   // linear between samples: no 20 Hz stepping on the lips
}
function updateSpeech(t, dt) {
  const env = envelopeNow(performance.now());
  mouth = dt > 0 ? damp(mouth, env, env > mouth ? SPEECH.attack : SPEECH.release, dt) : env;
  mouthOh = dt > 0 ? damp(mouthOh, env * env, 6, dt) : env * env; // low-passed harder: follows the swells, not the syllables
  const talking = !!speech;
  p.nod = talking ? Math.sin(t * 3.2) * 0.35 * (0.4 + 0.6 * mouth) : damp(p.nod, 0, 6, dt);
  gazeUp = damp(gazeUp, talking && p.typing > 0.5 && p.yaw < 0.15 ? 1 : 0, 4, dt);
}

// =====================================================================
// Pose: legs seated, torso/head, arms blended between "typing" and "rest",
// fingers driven by a per-finger key-press scheduler
// =====================================================================
// measured in rig space: fingertips land on the keyboard (z≈0.38, y≈0.8); rest = hands on the lap
// lower arm uses Euler order YXZ, so x = forearm roll (pronation): 1.0 turns the palms down onto the keys
// arms raised 0.1 rad and elbows bent 0.12 rad more than the first fit: measured with checkFingerClearance() so the lowest
// hand vertex sits ~18 mm above the key tops at rest and ~+1 mm at the peak of a press (fingers never enter the keys)
const ARM_TYPING = { upper: [-0.5, -0.3, -1.05], lower: [1.0, -1.51, -0.1], hand: [0, 0, 0.1] };
const ARM_REST = { upper: [-0.1, -0.2, -1.3], lower: [0.3, -1.3, 0], hand: [0, 0, -0.1] };
const mix3 = (a, b, k) => [lerp(a[0], b[0], k), lerp(a[1], b[1], k), lerp(a[2], b[2], k)];
const mirror = ([x, y, z]) => [x, -y, -z];

const press = { left: {}, right: {} };
const nextTap = { left: 0.3, right: 0.55 };
const FINGER_WEIGHTS = [0.08, 0.32, 0.28, 0.2, 0.12]; // thumb, index, middle, ring, little
function pickFinger() { let r = Math.random(), i = 0; while (r > FINGER_WEIGHTS[i]) { r -= FINGER_WEIGHTS[i]; i++; } return FINGERS[i]; }
// key press envelope: 0 → 1 → 0 over 180 ms (down 70 ms ease-out, up 110 ms ease-in-out). At 30 fps a 40 ms attack was
// 1 frame = a visible pop; the per-finger values are additionally damped (below) so no joint ever jumps between frames.
const PRESS_DOWN = 0.07, PRESS_UP = 0.11;
function pressCurve(t) {
  if (t < 0 || t > PRESS_DOWN + PRESS_UP) return 0;
  return t < PRESS_DOWN ? EASE.out(t / PRESS_DOWN) : 1 - EASE.sine((t - PRESS_DOWN) / PRESS_UP);
}
const fingerVal = { left: {}, right: {} }, dipVal = { left: 0, right: 0 }; // smoothed press values per finger / wrist
let forcePress = null; // dev: when not null, every finger/wrist uses this press value (0..1) — used by checkFingerClearance()
const FINGER_CURL = { base: 0.35, press: 0.35 }; // proximal curl at rest over the keys / extra curl at the peak of a press
const LEAN_ELBOW = -0.6, LEAN_PITCH_COMP = 0.5; // per unit of lean: extra elbow flex / shoulder counter-pitch (keeps the fingertips over the keys while leaning in)
const X_AXIS = new THREE.Vector3(1, 0, 0), qTmp = new THREE.Quaternion();
const FACE = { lids: 0.3, lidsGlance: 0.12, brows: 0.1, alert: 0.25, smirk: 0.7 }; // brows: "angry" > 0.15 drags the brows onto the lids on this model
let smirkTargets = []; // custom one-sided "happy" morph (her left mouth corner), built in addSmirkMorph()
// Stand-in tweaks (recolour, mole, collar, strips, makeup, sleeves, bangs, smirk) only for the sample model;
// the headset, mic and cursor earring are added to every model.
const STAND_IN = opts.standInTweaks ?? /sample\.vrm(\?|$)/i.test(opts.modelUrl);
let bangsReport = null; // measurements of the procedural bangs (dev)
let bodyMesh = null;   // Body_00_SKIN (hands + fingers live here), for checkFingerClearance()
function scheduleTaps(t) {
  const rate = p.tapRate * p.typing;
  for (const side of ['left', 'right']) {
    if (rate < 0.3) { nextTap[side] = t + 0.2; continue; }
    if (t >= nextTap[side]) {
      let f = pickFinger();
      if (t - (press[side][f] ?? -9) < 0.25) f = pickFinger(); // don't restart a finger mid-press (that restarts its curve = a jump)
      if (t - (press[side][f] ?? -9) >= 0.25) press[side][f] = t;
      nextTap[side] = t + (-Math.log(1 - Math.random()) / rate) + 0.08;
    }
  }
}

let blinkT = 0, nextBlink = 2.5, blinkDouble = false;
// --- fingertip clearance constraint (see the end of the arm loop in applyPose) ---
const ARM_LIFT_RADIUS = 0.42;      // shoulder → fingertip distance (m): angle = height / radius
const liftAng = { left: 0, right: 0 };
const _a = new THREE.Vector3();
// Uses the real skinned vertices of the hand, not a bone estimate: with relaxed fingers the lowest
// point is the finger pad / thumb, which a bone-tip estimate missed by up to 15 mm.
function fingerPenetration(side) {
  if (!bodyMesh) return 0;
  if (!handVerts) buildHandVerts();
  vrm.humanoid.update();                       // normalized → raw bones (applyPose runs before vrm.update)
  vrm.scene.updateMatrixWorld(true); bodyMesh.skeleton.update();
  let lowest = Infinity;
  for (let n = 0; n < handVerts.length; n++) { // all of them: sampling every 2nd missed one by 0.4 mm
    const [i, sd] = handVerts[n];
    if (sd !== side) continue;
    bodyMesh.getVertexPosition(i, _a).applyMatrix4(bodyMesh.matrixWorld); keyboard.worldToLocal(_a);
    if (Math.abs(_a.x) > KB.w / 2 + 0.01 || Math.abs(_a.z) > KB.d / 2 + 0.01 || _a.y < -0.05) continue; // not over the keys
    lowest = Math.min(lowest, _a.y);
  }
  return lowest === Infinity ? 0 : Math.max(0, KEY_TOP + 0.003 - lowest) * 1.1; // 3 mm margin, 10% for the arc
}

function applyPose(t, dt) {
  const B = bones;
  updateSpeech(t, dt);
  seat.rotation.y = p.spin;
  // legs: seated, knees slightly apart
  B.leftUpperLeg.rotation.set(-1.5, 0, -0.06); B.rightUpperLeg.rotation.set(-1.5, 0, 0.06);
  B.leftLowerLeg.rotation.set(1.55, 0, 0); B.rightLowerLeg.rotation.set(1.55, 0, 0);
  // torso: breathing (ambient), lean, turn toward camera (her left = +yaw), small nod while talking
  const breath = Math.sin(t * 1.6) * 0.018;
  B.spine.rotation.set(0.08 + p.lean * 0.5 + breath, p.yaw * 0.15, 0);
  B.chest.rotation.set(0.04 + p.lean * 0.3 + breath, p.yaw * 0.15, 0);
  if (B.upperChest) B.upperChest.rotation.set(0, p.yaw * 0.1, 0);
  // the head turns less than before (0.4 → 0.26 of yaw) so the eyes do more of the work: a sidelong glance, not a full turn
  B.neck.rotation.set(-0.05 - p.lean * 0.25, p.yaw * 0.22, 0);
  B.head.rotation.set(0.05 + Math.sin(t * 0.7) * 0.012 + p.nod * 0.06 - gazeUp * SPEECH.gazeLift, p.yaw * 0.26, Math.sin(t * 0.5) * 0.015);

  // arms
  const k = p.rest;
  const sway = Math.sin(t * 0.9) * 0.025 * (1 - k); // hands drift a little across the keys
  for (const side of ['left', 'right']) {
    const s = side === 'left' ? 1 : -1;
    const fix = (v) => (s > 0 ? v : mirror(v));
    let up = fix(mix3(ARM_TYPING.upper, ARM_REST.upper, k));
    up[1] += sway * s;
    const lo = mix3(ARM_TYPING.lower, ARM_REST.lower, k);
    lo[1] += LEAN_ELBOW * p.lean * (1 - k); // leaning in: bend the elbows a bit more so the hands stay over the keys, not past them
    B[`${side}UpperArm`].rotation.set(...up);
    // the spine+chest lean (0.8·lean rad of pitch) would carry the whole arm down through the desk: cancel that pitch
    // at the shoulder (rotation about the parent's X axis), so leaning moves the hands forward but not down
    B[`${side}UpperArm`].quaternion.premultiply(qTmp.setFromAxisAngle(X_AXIS, -LEAN_PITCH_COMP * p.lean * (1 - k)));
    B[`${side}LowerArm`].rotation.set(...fix(lo));
    // wrist: tiny dip on each key press (damped, small amplitude)
    let dip = 0;
    for (const f of FINGERS) dip = Math.max(dip, pressCurve(t - (press[side][f] ?? -9)));
    dipVal[side] = forcePress !== null ? forcePress : damp(dipVal[side], dip, 20, dt);
    const hand = fix(mix3(ARM_TYPING.hand, ARM_REST.hand, k));
    hand[2] += -s * dipVal[side] * 0.025 * (1 - k);
    B[`${side}Hand`].rotation.set(...hand);
    // fingers: relaxed curl over the keys, extra curl on press; each finger value is damped (~35 ms time constant).
    // Fixed rule: fingertips never go below the key tops — amplitudes below are validated by checkFingerClearance().
    for (const f of FINGERS) {
      fingerVal[side][f] = forcePress !== null ? forcePress : damp(fingerVal[side][f] ?? 0, pressCurve(t - (press[side][f] ?? -9)), 28, dt);
      const pr = fingerVal[side][f] * (1 - k);
      if (f === 'Thumb') {
        B[`${side}ThumbProximal`]?.rotation.set(0, -s * (0.25 + pr * 0.3), 0);
        B[`${side}ThumbDistal`]?.rotation.set(0, -s * 0.2, 0);
        continue;
      }
      const base = lerp(FINGER_CURL.base, 0.25, k);
      B[`${side}${f}Proximal`]?.rotation.set(0, 0, -s * (base + pr * FINGER_CURL.press));
      B[`${side}${f}Intermediate`]?.rotation.set(0, 0, -s * (base + 0.2 + pr * FINGER_CURL.press * 0.7));
      B[`${side}${f}Distal`]?.rotation.set(0, 0, -s * (base * 0.8));
    }
    // Fixed rule, enforced every frame (not just tuned constants — sway/lean/press phase made those fail by up to 22 mm):
    // estimate the fingertips from the bones; if any is below the key tops, lift the arm at the shoulder by exactly the
    // angle needed. Rises instantly (no frame inside the keys), settles back smoothly (no flicker).
    if (k < 0.999) {
      const needAng = fingerPenetration(side) / ARM_LIFT_RADIUS;
      liftAng[side] = Math.max(needAng, dt > 0 ? damp(liftAng[side], needAng, 6, dt) : needAng);
      if (liftAng[side] > 0) B[`${side}UpperArm`].quaternion.premultiply(qTmp.setFromAxisAngle(X_AXIS, -liftAng[side]));
    } else liftAng[side] = 0;
  }

  // face — personality (PERSONAGEM §2): calm, dry, serious. Heavy lids, straight/low brows, closed neutral mouth;
  // alert = attention, not a startle; the one-sided half-smile (smirk morph) is the rare "joke".
  const em = vrm.expressionManager;
  blinkT += dt;
  let blink = 0;
  if (blinkT > nextBlink) {
    const kk = (blinkT - nextBlink) / 0.14;
    blink = kk < 1 ? Math.sin(kk * Math.PI) : 0;
    if (kk >= 1) { blinkT = 0; nextBlink = blinkDouble ? 0.12 : 3 + Math.random() * 3; blinkDouble = !blinkDouble && Math.random() < 0.2; }
  }
  const lids = FACE.lids * (1 - 0.7 * p.surprised) + FACE.lidsGlance * Math.min(1, p.yaw / 0.3); // even heavier when she looks at you from the corner of her eye
  em.setValue('blink', Math.max(lids, blink));
  em.setValue('angry', FACE.brows * (1 - 0.5 * p.surprised)); // small weight = straight, slightly lowered brows (not a frown)
  em.setValue('surprised', p.surprised * FACE.alert);          // brows up a little, eyes open a little
  em.setValue('relaxed', 0);                                   // the model's "relaxed" is a closed-eye smile: not her
  for (const sm of smirkTargets) sm.mesh.morphTargetInfluences[sm.idx] = FACE.smirk * p.smirk;
  em.setValue('aa', mouth * SPEECH.maxAa);
  em.setValue('oh', mouthOh * SPEECH.maxOh);

  // neon: headphone rings + jacket strips follow "glow"; the cursor pendant blinks like a caret
  neonMat.color.set(COLORS.neon).multiplyScalar(1.8 * (0.25 + 0.75 * p.glow)); // > 1: only the neon blooms
  if (jacketMat) jacketMat.emissive.set(COLORS.neon).multiplyScalar(1.8 * (0.25 + 0.75 * p.glow));
  // leaning in (analyzing) brings the face from ~0.36 m to ~0.29 m of the monitor light (1.5× brighter): compensate so it doesn't blow out
  monitorLight.intensity = MONITOR_LIGHT_I / (1 + 1.6 * Math.max(0, p.lean));
  const caretHz = state === 'analyzing' ? 2 : 1;
  const caret = 0.5 + 0.5 * Math.sin(t * Math.PI * 2 * caretHz);
  cursorMat.color.set(COLORS.neon).multiplyScalar(2.0 * (0.15 + 0.85 * EASE.sine(caret)) * (0.3 + 0.7 * p.glow));
  // keyboard/mouse LEDs: slow "breathing" (8 s cycle, sine ease), a bit brighter while analyzing
  const breathe = EASE.sine(0.5 + 0.5 * Math.sin(t * Math.PI * 2 / 8));
  ledMat.color.set(COLORS.primary).multiplyScalar((0.55 + 0.45 * breathe) * (state === 'analyzing' ? 1.15 : 1));
}

// ---------- per-frame state logic ----------
const lookMonitor = new THREE.Vector3();
function updateState(dt) {
  stateTime += dt;
  const ms = stateTime * 1000;
  for (let i = timeline.length - 1; i >= 0; i--) if (ms >= timeline[i].at) { const ev = timeline[i]; timeline.splice(i, 1); ev.fn(); }

  let lookCam = state === 'alert' || (state === 'intro' && ms > 1450);
  if (state === 'intro') {
    const k = Math.min(1, stateTime / 2.6);
    camera.position.lerpVectors(CAM_START, CAM_FINAL, EASE.out(k)); // slow dolly-in
  } else if (state === 'idle') {
    // idle rhythm: type in bursts, pause; some pauses she glances at you with a dry half-smile
    if (stateTime > idleBeat) {
      const typingBurst = p.typing < 0.5;
      if (typingBurst) { go('typing', 1, DUR.std); go('yaw', 0, DUR.std); go('smirk', 0, DUR.slow); go('lean', 0, DUR.slow); idleBeat = stateTime + 3 + Math.random() * 3; }
      else {
        go('typing', 0, DUR.std);
        // some pauses she glances at you (sidelong, lids heavy); about 1 in 4 of those glances gets the dry half-smile
        if (Math.random() < 0.4) { go('yaw', 0.3, DUR.slow, EASE.std, 200); if (Math.random() < 0.25) go('smirk', 1, DUR.slow, EASE.std, 400); }
        else go('lean', -0.06, DUR.slow);
        idleBeat = stateTime + 1.6 + Math.random() * 1.6;
      }
    }
    lookCam = p.yaw > 0.15;
  }
  rig.localToWorld(lookMonitor.set(MONITOR.x + 0.05, MONITOR.yCenter + 0.02 + gazeUp * 0.09, MONITOR.z)); // she reads the screen slightly left of its centre; speaking, her eyes lift off it
  lookTarget.position.copy(lookCam ? camera.position : lookMonitor);
  scheduleTaps(performance.now() / 1000);
}

